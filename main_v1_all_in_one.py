class ResearchResponse(BaseModel):
    """Represent a structured research response generated by the assistant."""

    answer: str = Field(
        description="The answer to the user's research question."
    )
    confidence: str = Field(
        description="The confidence level of the answer: high, medium, or low."
    )
    confidence_percentage: float = Field(
        description=(
            "The system's estimated confidence in the answer, expressed "
            "as a percentage between 0 and 100."
        ),
        ge=0,
        le=100,
    )
    sources: List[str] = Field(
        description="A list of source documents used to generate the answer."
    )
    key_quotes: List[str] = Field(
        default_factory=list,
        description="Relevant quotations extracted from the source documents.",
    )
    follow_up_questions: List[str] = Field(
        default_factory=list,
        description="Suggested follow-up questions for further research.",
    )


class AIResearchAssistant:
    """Manage document ingestion, vector storage, retrieval, and conversations."""

    def __init__(
        self,
        persist_dir: str = "./research_db",
        chunk_size: int = 1000,
        chunk_overlap: int = 200,
    ) -> None:
        """Initialize the embedding model, text splitter, and vector store."""

        if chunk_size <= 0:
            raise ValueError("chunk_size must be greater than zero.")

        if chunk_overlap < 0 or chunk_overlap >= chunk_size:
            raise ValueError(
                "chunk_overlap must be non-negative and smaller than chunk_size."
            )

        self.persist_dir = persist_dir

        self.llm = ChatOllama(
            model="deepseek-r1:7b-qwen-distill-q4_k_m"
        )

        self.embeddings_model = OllamaEmbeddings(
            model="nomic-embed-text:latest"
        )

        self.splitter = RecursiveCharacterTextSplitter(
            chunk_size=chunk_size,
            chunk_overlap=chunk_overlap,
            separators=["\n\n", "\n", ". ", " ", ""],
        )

        self.vector_store = Chroma(
            persist_directory=self.persist_dir,
            embedding_function=self.embeddings_model,
            collection_name="research_doc",
        )

        self.retriever = self._build_retriever()

        self.session_store: Dict[str, InMemoryChatMessageHistory] = {}

    def reset_vector_store(self) -> None:
        """Delete the existing collection and recreate an empty one."""

        self.vector_store.reset_collection()
        self.retriever = self._build_retriever()

        print("Vector store reset successfully.")

    def add_text(
        self,
        text: str,
        source: str,
        metadata: Optional[Dict] = None,
    ) -> int:
        """Add a single text document to the vector store."""

        document = Document(
            page_content=text,
            metadata={
                "source": source,
                **(metadata or {}),
            },
        )

        return self.add_documents([document])

    def add_texts(
        self,
        texts: List[str],
        source: str,
    ) -> int:
        """Add multiple text documents sharing the same source."""

        documents = [
            Document(
                page_content=text,
                metadata={"source": source},
            )
            for text in texts
        ]

        return self.add_documents(documents)

    def add_documents(
        self,
        documents: List[Document],
        source_name: Optional[str] = None,
    ) -> int:
        """Split documents into chunks and store them in Chroma."""

        if not documents:
            return 0

        for document in documents:
            if source_name:
                document.metadata["source"] = source_name
            else:
                document.metadata.setdefault("source", "unknown")

        chunks = self.splitter.split_documents(documents)

        indexed_at = datetime.now().isoformat()

        for index, chunk in enumerate(chunks):
            chunk.metadata["indexed_at"] = indexed_at
            chunk.metadata["chunk_index"] = index

        if chunks:
            self.vector_store.add_documents(chunks)

            print(
                f"Added {len(chunks)} chunks "
                f"from {len(documents)} documents."
            )

        return len(chunks)

    def get_document_count(self) -> int:
        """Return the total number of stored chunks."""

        return self.vector_store._collection.count()

    def list_sources(self) -> List[str]:
        """Return sorted, unique source names from stored metadata."""

        results = self.vector_store._collection.get()
        metadatas = results.get("metadatas") or []

        sources = set()

        for metadata in metadatas:
            source = metadata.get("source") if metadata else None

            if isinstance(source, str) and source:
                sources.add(source)

        return sorted(sources)

    def _build_retriever(self):
        """Build a similarity-based retriever."""

        return self.vector_store.as_retriever(
            search_type="similarity",
            search_kwargs={"k": 4},
        )

    def _get_session_history(
        self,
        session_id: str,
    ) -> BaseChatMessageHistory:
        """Retrieve an existing session or create a new one."""

        if session_id not in self.session_store:
            self.session_store[session_id] = InMemoryChatMessageHistory()

        return self.session_store[session_id]

    def clear_session(self, session_id: str) -> None:
        """Clear conversation history for a specific session."""

        if session_id in self.session_store:
            self.session_store[session_id].clear()
            print(f"Cleared Session: {session_id}")

    def get_session_history_display(
        self,
        session_id: str,
    ) -> List[Dict[str, str | Any]]:
        """Return formatted conversation history for display."""

        if session_id not in self.session_store:
            return []

        return [
            {
                "role": (
                    "human"
                    if isinstance(message, HumanMessage)
                    else "assistant"
                ),
                "content": message.content,
            }
            for message in self.session_store[session_id].messages
        ]

    def search(self, query: str) -> List[Document]:
        """Retrieve relevant document chunks for a query."""

        return self.retriever.invoke(query)

    def ask(
        self,
        question: str,
        session_id: str = "session_id",
    ) -> str:
        """Retrieve relevant documents and generate a contextual answer."""

        history = self._get_session_history(session_id)

        docs = self.search(question)

        context = format_search_results(docs)

        prompt = ChatPromptTemplate.from_messages(
            [
                (
                    "system",
                    "You are an AI research assistant. "
                    "Answer the user's question using the provided context. "
                    "All answers must be supported by the sources of the answer. "
                    "If the context doesn't contain the answer, "
                    "clearly state that you don't have enough information.\n\n"
                    "Context:\n{context}",
                ),
                MessagesPlaceholder(variable_name="history"),
                ("human", "{question}"),
            ]
        )

        chain = prompt | self.llm | StrOutputParser()

        response = chain.invoke(
            {
                "context": context,
                "question": question,
                "history": history.messages[-10:],
            }
        )

        history.add_messages(
            [
                HumanMessage(content=question),
                AIMessage(content=response),
            ]
        )

        return response


