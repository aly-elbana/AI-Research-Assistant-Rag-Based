class AIResearchAssistant:
    """Manage document ingestion, vector storage, and retrieval."""

    def __init__(
        self,
        persist_dir: str = "./research_db",
        chunk_size: int = 1000,
        chunk_overlap: int = 200,
    ) -> None:
        """Initialize the embedding model, text splitter, and vector store."""

        if chunk_size <= 0:
            raise ValueError("chunk_size must be greater than zero.")

        if chunk_overlap < 0 or chunk_overlap >= chunk_size:
            raise ValueError(
                "chunk_overlap must be non-negative and smaller than chunk_size."
            )

        self.persist_dir = persist_dir

        self.llm = ChatOllama(
            model="deepseek-r1:7b-qwen-distill-q4_k_m"
        )

        self.embeddings_model = OllamaEmbeddings(
            model="nomic-embed-text:latest"
        )
        
        self.splitter = RecursiveCharacterTextSplitter(
            chunk_size=chunk_size,
            chunk_overlap=chunk_overlap,
            separators=["\n\n", "\n", ". ", " ", ""],
        )

        self.vector_store = Chroma(
            persist_directory=self.persist_dir,
            embedding_function=self.embeddings_model,
            collection_name="research_doc",
        )
        
        self.retriever = self._build_retriever()

    def reset_vector_store(self) -> None:
        """Delete the existing collection and recreate an empty one."""

        self.vector_store.reset_collection()

        self.retriever = self._build_retriever()
        
        print("Vector store reset successfully.")

    def add_text(
        self,
        text: str,
        source: str,
        metadata: Optional[Dict] = None,
    ) -> int:
        """Add a single text document to the vector store."""

        document = Document(
            page_content=text,
            metadata={
                "source": source,
                **(metadata or {}),
            },
        )

        return self.add_documents([document])

    def add_texts(
        self,
        texts: List[str],
        source: str,
    ) -> int:
        """Add multiple text documents sharing the same source."""

        documents = [
            Document(
                page_content=text,
                metadata={"source": source},
            )
            for text in texts
        ]

        return self.add_documents(documents)

    def add_documents(
        self,
        documents: List[Document],
        source_name: Optional[str] = None,
    ) -> int:
        """Split documents into chunks and store them in Chroma."""

        if not documents:
            return 0

        for document in documents:
            if source_name:
                document.metadata["source"] = source_name
            else:
                document.metadata.setdefault("source", "unknown")

        chunks = self.splitter.split_documents(documents)

        indexed_at = datetime.now().isoformat()

        for index, chunk in enumerate(chunks):
            chunk.metadata["indexed_at"] = indexed_at
            chunk.metadata["chunk_index"] = index

        if chunks:
            self.vector_store.add_documents(chunks)

            print(
                f"Added {len(chunks)} chunks "
                f"from {len(documents)} documents."
            )

        return len(chunks)

    def get_document_count(self) -> int:
        """Return the total number of stored chunks."""

        return self.vector_store._collection.count()

    def list_sources(self) -> List[str]:
        """Return sorted, unique source names from stored metadata."""

        results = self.vector_store._collection.get()
        metadatas = results.get("metadatas") or []

        sources = set()

        for metadata in metadatas:
            source = metadata.get("source") if metadata else None

            if isinstance(source, str) and source:
                sources.add(source)

        return sorted(sources)

    def _build_retriever(self):
        """Build a similarity-based retriever."""

        return self.vector_store.as_retriever(
            search_type="similarity",
            search_kwargs={"k": 4},
        )

    def search(self, query: str) -> List[Document]:
        """Retrieve relevant document chunks for a query."""

        return self.retriever.invoke(query)


